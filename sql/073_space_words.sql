-- Space-themed vocabulary for scooter identities.
--
-- Riders and vehicles both get a memorable two-part name, but they must not be
-- confusable: an account is "Resourceful 🌈" from sfw_adjectives, a scooter is
-- "Lunar 🐸" from this table. Same shape, unmistakably different species.
--
-- Paired with the existing emoji_nouns (181 entries) this gives 33,485
-- combinations for ~8,000 active vehicles. Names are DERIVED from the
-- vehicle_identifier rather than assigned (see src/vehicle_identity.py), so
-- there is no assignment job, no state to keep in sync, and a scooter carries
-- the same name for its whole life. The cost of deriving rather than
-- assigning is that duplicates are possible city-wide; what matters is the
-- handful of scooters a rider can see at once, where a collision is
-- vanishingly unlikely.

CREATE TABLE IF NOT EXISTS space_words (
    word TEXT PRIMARY KEY
);

