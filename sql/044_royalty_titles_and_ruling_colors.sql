ALTER TABLE accounts
    ADD COLUMN IF NOT EXISTS royalty_title       TEXT REFERENCES royalty_titles(title),
    ADD COLUMN IF NOT EXISTS ruling_color        TEXT REFERENCES ruling_colors(hex),
    ADD COLUMN IF NOT EXISTS ruling_border_color TEXT REFERENCES ruling_colors(hex),
    ADD COLUMN IF NOT EXISTS ruling_alpha        NUMERIC(3,2) NOT NULL DEFAULT 0.60
        CONSTRAINT accounts_ruling_alpha_range
        CHECK (ruling_alpha BETWEEN 0.10 AND 1.00);

-- Fill and border are set together or not at all, and must differ: a
-- border the same colour as its fill is not a border, and would silently
-- consume one of the 16 256 pair claims to render as a plain block.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'accounts_ruling_colors_coherent'
          AND conrelid = 'accounts'::regclass AND contype = 'c'
    ) THEN
        ALTER TABLE accounts
            ADD CONSTRAINT accounts_ruling_colors_coherent CHECK (
                (ruling_color IS NULL AND ruling_border_color IS NULL) OR
                (ruling_color IS NOT NULL AND ruling_border_color IS NOT NULL
                 AND ruling_color <> ruling_border_color)
            );
    END IF;
END $$;

-- The pair claim. Partial so the (NULL, NULL) accounts — every account
-- before it picks colours — do not contend for a single slot.
CREATE UNIQUE INDEX IF NOT EXISTS accounts_ruling_pair_key
    ON accounts (ruling_color, ruling_border_color)
    WHERE ruling_color IS NOT NULL AND ruling_border_color IS NOT NULL;

-- Title + existing public username. See the header for why this reads the
-- parts rather than public_username.
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS display_name TEXT
    GENERATED ALWAYS AS (
        COALESCE(royalty_title || ' ', '') || username_adjective || username_emoji
    ) STORED;
