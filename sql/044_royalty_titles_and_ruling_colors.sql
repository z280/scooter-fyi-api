-- Royalty titles + ruling colours: the two decorative identity fields
-- behind the leaderboard map, plus the display_name they compose into.
--
-- Both are CURATED LISTS with FK references, exactly like sql/025's
-- sfw_adjectives/emoji_nouns, and for the same two reasons: a rider
-- cannot type free text into a field that renders on a public map, and
-- the list can be extended by a later migration without a code change.
--
-- WHAT DISPLAY_NAME IS
-- --------------------
-- "King brave-owl-emoji" — the title, a space, then the existing
-- adjective+emoji public username. It is built from the PARTS
-- (royalty_title, username_adjective, username_emoji) and NOT from
-- public_username, because Postgres forbids a stored generated column
-- referencing another stored generated column. Same NULL propagation as
-- public_username: an account that has not been backfilled a username has
-- neither field.
--
-- display_name is deliberately NOT unique. public_username keeps its
-- uniqueness and remains the identity key; the title is decoration, and
-- two riders styling themselves King with different animals is fine.
--
-- WHY THE COLOUR PAIR IS UNIQUE AND THE COLOURS ARE NOT
-- -----------------------------------------------------
-- The leaderboard map colours each hexagon by whoever leads it. Two
-- riders whose territories render identically make that map unreadable
-- precisely where it is most interesting — adjacent cells. So the
-- (fill, border) PAIR is globally unique, which is 128 x 127 = 16 256
-- distinct claims rather than the 128 a unique fill alone would allow.
-- Riders may share a fill or share a border, just not both.
--
-- ALPHA governs the FILL only; the border renders opaque. A border whose
-- whole job is separating adjacent territories should not be able to fade
-- out. The 0.10 floor is for the same reason — a fully transparent
-- territory is an invisible one, and opting out of the map already has a
-- home in accounts.show_in_leaderboards.

CREATE TABLE IF NOT EXISTS royalty_titles (
    title       TEXT PRIMARY KEY,
    sort_order  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS ruling_colors (
    hex         TEXT PRIMARY KEY
                CONSTRAINT ruling_colors_hex_format
                CHECK (hex ~ '^#[0-9a-f]{6}$'),
    name        TEXT NOT NULL,          -- 'crimson-500'
    hue_family  TEXT NOT NULL,          -- picker grouping
    sort_order  INTEGER NOT NULL
);

